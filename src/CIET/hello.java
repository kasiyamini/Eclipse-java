package CIET;
/*
 *  Assignment operator
 *  = Assign ex:-a=10
 *  += add and assign a+=5 a=a+5
 *  -= subtract ans assign a-=5 a=a-5
 *  *= multiply and assign
 *  /= divide and assign
 *  %= modulus and assign
 */

public class hello {
      public static void main(String[] args) {
    	  byte a = 12;
    	  byte b = 2;
    	  System.out.println(a==b);
    	  System.out.println(a<=b);
    	  System.out.println(a>=b);
    	  System.out.println(a!=b);
    	  System.out.println(a>b);
      }
      
}
